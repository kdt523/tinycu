#!/usr/bin/env python3
"""Turns gcovr's --json-summary into results/coverage.md (per directory and total)."""
import json
import sys
from collections import defaultdict

data = json.load(open(sys.argv[1]))
fuzz_n = sys.argv[2] if len(sys.argv) > 2 else "?"
dirs = defaultdict(lambda: [0, 0])
for f in data["files"]:
    d = "/".join(f["filename"].split("/")[:2])
    dirs[d][0] += f["line_covered"]
    dirs[d][1] += f["line_total"]
print("# Line coverage")
print()
print("Generated by `tools/coverage.sh`; do not edit by hand.")
print()
print(f"Workload: all ctest tests (unit, golden, error, warning) + {fuzz_n} fuzz programs (A vs B).")
print()
print("| directory | lines covered | lines | coverage |")
print("|---|---:|---:|---:|")
for d in sorted(dirs):
    c, t = dirs[d]
    print(f"| {d} | {c} | {t} | {c / t * 100:.1f}% |")
print(f"| **total** | {data['line_covered']} | {data['line_total']} | **{data['line_percent']:.1f}%** |")
