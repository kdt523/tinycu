"""Measured impact of -O1: PTX instructions, declared PTX registers, ptxas registers, SASS.

    python -m tcharness.optstats [--sm sm_75] [--out results/opt_impact.md] [files...]

Reports per kernel and in total, at -O0 and -O1. ptxas optimizes on its own (it builds SSA,
folds constants, removes dead code), so the PTX-level reduction is expected to be larger than
the SASS-level one; both are reported, as measured.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from tcharness.ptxstats import collect, default_files
from tcharness.tinycu import compile as tc_compile


def declared_regs(ptx: str) -> dict[str, int]:
    """Sum of the `.reg .X %r<N>` declarations (N-1 registers each) per kernel."""
    out: dict[str, int] = {}
    kernel = None
    for line in ptx.splitlines():
        m = re.match(r"\.visible \.entry (\w+)\(", line)
        if m:
            kernel = m.group(1)
            out[kernel] = 0
        m = re.search(r"\.reg \.\w+\s+%\w+<(\d+)>", line)
        if m and kernel:
            out[kernel] += int(m.group(1)) - 1
    return out


def pct(before: int, after: int) -> str:
    return "n/a" if before == 0 else f"{(before - after) / before * 100:+.1f}%".replace("+", "−", 1) \
        if after < before else f"{(after - before) / before * 100:+.1f}%"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("files", nargs="*", type=Path)
    ap.add_argument("--sm", default="sm_75")
    ap.add_argument("--out", type=Path)
    a = ap.parse_args(argv)
    files = a.files or default_files()

    rows0, _ = collect(files, 0, a.sm)
    rows1, _ = collect(files, 1, a.sm)
    vregs = {}
    for opt in (0, 1):
        for tc in files:
            for k, n in declared_regs(tc_compile(tc, emit="ptx", opt=opt, extra=[f"--sm={a.sm}"])).items():
                vregs[(tc.name, k, opt)] = n

    md = [f"# Impact of -O1 ({a.sm})", "",
          "Generated by `python -m tcharness.optstats`; do not edit by hand.", "",
          "PTX instrs = instructions in TinyCU's PTX; PTX regs = virtual registers declared; "
          "ptxas regs = physical registers after ptxas (`-v`); SASS = machine instructions "
          "(padding excluded).", "",
          "| file | kernel | PTX instrs O0 → O1 | PTX regs O0 → O1 | ptxas regs O0 → O1 | SASS O0 → O1 |",
          "|---|---|---:|---:|---:|---:|"]
    tot = {"p0": 0, "p1": 0, "v0": 0, "v1": 0, "r0": 0, "r1": 0, "s0": 0, "s1": 0}
    for r0, r1 in zip(rows0, rows1):
        v0, v1 = vregs[(r0.file, r0.kernel, 0)], vregs[(r1.file, r1.kernel, 1)]
        md.append(f"| {r0.file} | {r0.kernel} | {r0.ptx_instrs} → {r1.ptx_instrs} | {v0} → {v1} | "
                  f"{r0.regs} → {r1.regs} | {r0.sass_instrs} → {r1.sass_instrs} |")
        for key, x, y in (("p", r0.ptx_instrs, r1.ptx_instrs), ("v", v0, v1), ("r", r0.regs, r1.regs),
                          ("s", r0.sass_instrs, r1.sass_instrs)):
            tot[key + "0"] += x
            tot[key + "1"] += y
    md += ["", f"**Totals over {len(rows0)} kernels:**", "",
           "| metric | -O0 | -O1 | change |", "|---|---:|---:|---:|",
           f"| PTX instructions | {tot['p0']} | {tot['p1']} | {pct(tot['p0'], tot['p1'])} |",
           f"| PTX virtual registers | {tot['v0']} | {tot['v1']} | {pct(tot['v0'], tot['v1'])} |",
           f"| ptxas registers (sum) | {tot['r0']} | {tot['r1']} | {pct(tot['r0'], tot['r1'])} |",
           f"| SASS instructions | {tot['s0']} | {tot['s1']} | {pct(tot['s0'], tot['s1'])} |", "",
           "ptxas performs its own constant folding, copy propagation, dead-code elimination and "
           "register allocation on the PTX, so most of what -O1 removes at the PTX level would also "
           "have been removed by ptxas; the SASS column shows what is left of the effect.", ""]
    text = "\n".join(md)
    print(text)
    if a.out:
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(text)
        import json  # noqa: PLC0415
        a.out.with_suffix(".json").write_text(
            json.dumps({"kernels": len(rows0), "totals": tot}, indent=1) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
