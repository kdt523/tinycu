"""Planted-bug validation: does the fuzzer find deliberate miscompiles, and how fast?

    python -m tcharness.bug_injection [--n 2000] [--jobs 8] [--reduce 5] [--out results/bug_injection.md]

For each injected bug (tinycu --inject-bug=ID, see include/tinycu/opt.h) runs the fuzzer on the
same seeds, then reduces the first `--reduce` failing programs and bisects the culprit pass.
Reports: detected or not, failing programs, programs until the first detection (in seed
order), average reduction, and whether bisection named the right pass.
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

from tcharness import fuzz, reduce
from tcharness.tinycu import REPO_ROOT

BUGS = {
    1: ("constfold", "int add/sub/mul folded with saturation instead of wrap-around"),
    2: ("copyprop", "copy not invalidated when its source is redefined"),
    3: ("dce", "stores of constant values deleted"),
    4: ("simplifycfg", "condbr targets swapped while threading a jump"),
}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n", type=int, default=2000)
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--reduce", type=int, default=5, help="failing programs to reduce per bug")
    ap.add_argument("--work", type=Path, default=REPO_ROOT / "fuzz_out" / "bug_injection")
    ap.add_argument("--out", type=Path, default=REPO_ROOT / "results" / "bug_injection.md")
    a = ap.parse_args(argv)

    rows = []
    for bug, (pass_name, what) in BUGS.items():
        work = a.work / f"bug{bug}"
        shutil.rmtree(work, ignore_errors=True)
        s = fuzz.run(a.n, a.jobs, False, 0.3, 0, [f"--inject-bug={bug}"], work, quiet=True)
        failing = sorted(int(p.name) for p in work.iterdir() if p.is_dir())
        reductions = []
        culprit_ok = 0
        for seed in failing[:a.reduce]:
            r = reduce.run(work / str(seed), budget=3000, quiet=True)
            reductions.append(r)
            culprit_ok += r["culprit_passes"] == [pass_name]
        avg = sum(r["reduction"] for r in reductions) / len(reductions) if reductions else 0.0
        avg_nodes = sum(r["ast_reduction"] for r in reductions) / len(reductions) if reductions else 0.0
        row = {"bug": bug, "pass": pass_name, "description": what, "programs": s["programs"],
               "failing": len(failing), "detected": bool(failing),
               "first_detection": (failing[0] + 1) if failing else None,
               "labels": s["counts"], "reduced": len(reductions),
               "avg_reduction": round(avg, 3), "avg_ast_reduction": round(avg_nodes, 3),
               "culprit_correct": culprit_ok,
               "examples": [{"seed": r["seed"], "lines": f"{r['lines_before']} -> {r['lines_after']}",
                             "culprits": r["culprit_passes"]} for r in reductions]}
        rows.append(row)
        print(f"bug {bug} ({pass_name}): {len(failing)}/{s['programs']} failing, first at program "
              f"{row['first_detection']}, avg reduction {avg * 100:.0f}%, culprit correct "
              f"{culprit_ok}/{len(reductions)}", flush=True)

    detected = sum(r["detected"] for r in rows)
    all_red = [e for r in rows for e in r["examples"]]
    avg_all = (sum(r["avg_reduction"] * r["reduced"] for r in rows) / len(all_red)) if all_red else 0.0
    avg_nodes_all = (sum(r["avg_ast_reduction"] * r["reduced"] for r in rows) / len(all_red)) if all_red else 0.0
    summary = {"bugs": len(rows), "detected": detected, "programs_per_bug": a.n,
               "avg_reduction": round(avg_all, 3), "avg_ast_reduction": round(avg_nodes_all, 3),
               "culprit_correct": sum(r["culprit_correct"] for r in rows),
               "reduced_total": len(all_red), "rows": rows}
    md = ["# Planted-bug validation", "",
          "Generated by `python -m tcharness.bug_injection`; do not edit by hand.", "",
          f"**{detected}/{len(rows)} injected miscompiles detected** with {a.n} generated programs "
          f"each (paths A vs B); average reduction of the failing programs "
          f"**{avg_all * 100:.0f}% in source lines** / {avg_nodes_all * 100:.0f}% in AST nodes "
          f"({len(all_red)} reductions); pass bisection named the right pass in "
          f"{summary['culprit_correct']}/{len(all_red)} cases.", "",
          "Line counts include the fixed 7-line kernel wrapper every program has (signature, "
          "index computation, bounds guard); AST nodes count only the generated body.", "",
          "| bug | pass | injected defect | failing programs | first detection (program #) | avg reduction (lines) | avg reduction (AST nodes) | culprit correct |",
          "|---|---|---|---:|---:|---:|---:|---:|"]
    for r in rows:
        md.append(f"| {r['bug']} | {r['pass']} | {r['description']} | {r['failing']}/{r['programs']} | "
                  f"{r['first_detection'] or '—'} | {r['avg_reduction'] * 100:.0f}% | "
                  f"{r['avg_ast_reduction'] * 100:.0f}% | "
                  f"{r['culprit_correct']}/{r['reduced']} |")
    md += ["", "Reduced examples (lines of TinyCU source, before → after):", ""]
    for r in rows:
        md.append(f"- bug {r['bug']}: " + ", ".join(f"seed {e['seed']} {e['lines']}" for e in r["examples"]))
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(md) + "\n")
    a.out.with_suffix(".json").write_text(json.dumps(summary, indent=1) + "\n")
    print("\n".join(md))
    return 0 if detected == len(rows) else 1


if __name__ == "__main__":
    sys.exit(main())
