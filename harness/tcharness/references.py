"""Independent NumPy reference implementations of the kernel suite (tests/kernels/).

Each function takes the kernel arguments by parameter name (NumPy arrays / scalars, already
generated by `tcharness.suite`) and returns {output name: expected array}. Float math is done
in float32 in the same operation order as the kernel, so results are bit-exact.
"""
from __future__ import annotations

import numpy as np

F = np.float32
REFERENCES = {}


def ref(fn):
    REFERENCES[fn.__name__] = fn
    return fn


def _wrap_i32(v: np.ndarray) -> np.ndarray:
    return (np.asarray(v, dtype=np.int64) & 0xFFFFFFFF).astype(np.uint32).view(np.int32)


@ref
def vecadd_i32(a, b, c, n):
    return {"c": (a.astype(np.int64) + b).astype(np.int32)}


@ref
def vecadd_f32(a, b, c, n):
    return {"c": a + b}


@ref
def saxpy(a, x, y, n):
    return {"y": a * x + y}


@ref
def scale(x, s, n):
    return {"x": x * s}


@ref
def relu(x, y, n):
    return {"y": np.where(x < 0, F(0), x).astype(F)}


@ref
def leaky_relu(x, y, alpha, n):
    return {"y": np.where(x < 0, alpha * x, x).astype(F)}


@ref
def clamp(x, lo, hi, n):
    return {"x": np.minimum(np.maximum(x, lo), hi)}


@ref
def abs_diff(a, b, c, n):
    return {"c": np.abs(a - b)}


@ref
def square(x, y, n):
    return {"y": x * x}


@ref
def polynomial(x, y, n):
    return {"y": ((F(3) * x - F(2)) * x + F(0.5)) * x - F(7.25)}


@ref
def int_hash(x, h, n):
    v = x.astype(np.int64)
    v = (v * 1103515245 + 12345) & 0xFFFFFFFF
    v = (v * 1664525 + 1013904223 - np.arange(n, dtype=np.int64)) & 0xFFFFFFFF
    return {"h": _wrap_i32(v)}


@ref
def branchy(x, o, n):
    out = np.select([x < -25, x < 0, x == 0, ((x % 2 == 0) & (x > 10)) | (x == 7)],
                    [-2, -1, 0, 2], 1)
    return {"o": out.astype(np.int32)}


@ref
def loop_sum(x, o, n):
    table = np.cumsum([j * (j % 5) for j in range(int(x.max(initial=0)) + 1)])
    sums = np.where(x > 0, table[np.maximum(x - 1, 0)], 0)
    return {"o": sums.astype(np.int32)}


@ref
def while_collatz(x, steps, n):
    out = np.empty(n, np.int32)
    for k, v in enumerate(x.tolist()):
        c = 0
        while v != 1 and c < 1000:
            v = v // 2 if v % 2 == 0 else 3 * v + 1
            c += 1
        out[k] = c
    return {"steps": out}


@ref
def break_continue(x, o, n):
    out = [sum(j * j for j in range(v) if j % 3 != 0 and j <= 40) for v in x.tolist()]
    return {"o": np.array(out, np.int32)}


@ref
def stencil_1d(x, y, n):
    out = x.copy()
    if n > 2:
        out[1:-1] = F(0.25) * x[:-2] + F(0.5) * x[1:-1] + F(0.25) * x[2:]
    return {"y": out}


@ref
def grid_stride_loop(x, y, s, n):
    return {"y": x * s + F(1)}


@ref
def dot_partial(a, b, partial, n):
    chunks = (n + 15) // 16
    acc = np.zeros(chunks, F)
    prod = np.zeros(chunks * 16, F)
    prod[:n] = a * b
    prod = prod.reshape(chunks, 16)
    valid = (np.arange(chunks * 16) < n).reshape(chunks, 16)
    for j in range(16):  # same left-to-right accumulation as the kernel
        acc = np.where(valid[:, j], acc + prod[:, j], acc).astype(F)
    return {"partial": acc}


@ref
def matmul_naive(a, b, c, n):
    A, B = a.reshape(n, n), b.reshape(n, n)
    acc = np.zeros((n, n), F)
    for k in range(n):
        acc = acc + A[:, k:k + 1] * B[k:k + 1, :]
    return {"c": acc.reshape(-1)}


@ref
def softmax_row_max_sum(x, rmax, rsum, rows, cols):
    X = x.reshape(rows, cols)
    m = X[:, 0].copy()
    for j in range(1, cols):
        m = np.maximum(m, X[:, j])
    s = np.zeros(rows, F)
    for j in range(cols):
        s = s + (X[:, j] - m)
    return {"rmax": m, "rsum": s}


@ref
def transpose(inp, out, rows, cols):
    return {"out": inp.reshape(rows, cols).T.reshape(-1).copy()}


@ref
def reduce_shared(inp, out, n):
    block = 256
    nb = (n + block - 1) // block
    buf = np.zeros(nb * block, F)
    buf[:n] = inp
    buf = buf.reshape(nb, block)
    s = block // 2
    while s > 0:  # the same tree as the kernel
        buf[:, :s] = buf[:, :s] + buf[:, s:2 * s]
        s //= 2
    return {"out": buf[:, 0].copy()}
