"""Kernel timing: TinyCU PTX vs the CUDA twin compiled by NVRTC (default flags: -O3, FMA on).

    python -m tcharness.bench [--opt 1] [--repeat 20] [--matmul-n 4096] [--out results/bench.md]

This is a sanity check, not a goal: TinyCU has no loop unrolling, no `ld.global.nc`, no FMA
(by design, for bit-exactness) and no shared-memory tiling, so NVRTC is expected to be faster
on compute-bound kernels such as matmul. Times are the median of `--repeat` launches measured
with CUDA events (inputs are not re-uploaded between launches; all three kernels are
idempotent).
"""
from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

import numpy as np

from tcharness import suite
from tcharness.tinycu import compile as tc_compile

CASES = [("vecadd_f32", 1 << 24), ("saxpy", 1 << 24), ("matmul_naive", None)]


def median_ms(kernel, grid: int, block: int, args: tuple, repeat: int) -> float:
    import cupy as cp  # noqa: PLC0415
    kernel((grid,), (block,), args)  # warm-up (includes JIT)
    cp.cuda.Device().synchronize()
    times = []
    for _ in range(repeat):
        start, stop = cp.cuda.Event(), cp.cuda.Event()
        start.record()
        kernel((grid,), (block,), args)
        stop.record()
        stop.synchronize()
        times.append(cp.cuda.get_elapsed_time(start, stop))
    return float(np.median(times))


def main(argv: list[str] | None = None) -> int:
    import cupy as cp  # noqa: PLC0415
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--opt", type=int, default=1, choices=(0, 1))
    ap.add_argument("--repeat", type=int, default=20)
    ap.add_argument("--matmul-n", type=int, default=4096, help="matrix size (n*n = 2^24 by default)")
    ap.add_argument("--out", type=Path)
    a = ap.parse_args(argv)

    specs = {s.name: s for s in suite.load_specs([c[0] for c in CASES])}
    rows = []
    for name, n in CASES:
        spec = specs[name]
        n = n if n is not None else a.matmul_n
        args = suite.make_inputs(spec, n)
        dev = tuple(cp.asarray(x) if isinstance(x, np.ndarray) else x for x in args)
        with tempfile.TemporaryDirectory() as d:
            ptx = Path(d) / "k.ptx"
            ptx.write_text(tc_compile(spec.tc, emit="ptx", opt=a.opt))
            ours = cp.RawModule(path=str(ptx)).get_function(name)
            repeat = a.repeat if name != "matmul_naive" else max(3, a.repeat // 4)
            t_ours = median_ms(ours, spec.grid_for(n), spec.block, dev, repeat)
        nvrtc = suite.nvrtc_kernel(spec.cu.read_text(), name, ())  # NVRTC defaults: -O3, fmad=true
        t_nvrtc = median_ms(nvrtc, spec.grid_for(n), spec.block, dev, repeat)
        size = f"{n}x{n}" if name == "matmul_naive" else f"2^{int(np.log2(n))}"
        rows.append((name, size, t_ours, t_nvrtc))
        print(f"{name:14} {size:>10}  tinycu -O{a.opt}: {t_ours:9.3f} ms   nvrtc -O3: {t_nvrtc:9.3f} ms",
              flush=True)

    gpu = suite.gpu_name()
    md = [f"# Kernel timing: TinyCU -O{a.opt} vs NVRTC -O3", "",
          "Generated by `python -m tcharness.bench`; do not edit by hand.", "",
          f"GPU: {gpu}. Median of CUDA-event timings.", "",
          "| kernel | size | TinyCU (ms) | NVRTC (ms) | NVRTC speed-up |", "|---|---|---:|---:|---:|"]
    for name, size, t1, t2 in rows:
        md.append(f"| {name} | {size} | {t1:.3f} | {t2:.3f} | {t1 / t2:.2f}x |")
    md += ["", "Observed (computed from the table above):"]
    for name, size, t1, t2 in rows:
        rel = "faster" if t1 < t2 else "slower"
        md.append(f"- {name} ({size}): TinyCU is {abs(t2 - t1) / t2 * 100:.1f}% {rel} than NVRTC.")
    md += ["", "Context: vecadd and saxpy are memory-bound, so both compilers should be close. "
               "TinyCU emits no FMA (separate `.rn` mul/add, for bit-exactness), no loop unrolling "
               "and no `ld.global.nc`; any matmul difference should be explained from the SASS "
               "(`cuobjdump -sass`) before drawing conclusions. Laptop GPUs vary their clocks, so "
               "compare runs on the same machine only.", ""]
    text = "\n".join(md)
    print(text)
    if a.out:
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
