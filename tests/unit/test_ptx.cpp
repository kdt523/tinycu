using namespace tinycu;

namespace {

std::string toPtx(const std::string &src, const std::string &sm = "sm_75") {
  static std::string keep;
  keep = src;
  DiagEngine diag("t.tc", keep);
  auto prog = parseSource(keep, diag);
  EXPECT_FALSE(diag.hasErrors());
  EXPECT_TRUE(Sema(diag).run(*prog));
  auto m = lowerProgram(*prog);
  ptx::Options o;
  o.sm = sm;
  return ptx::emitModule(*m, o);
}

bool has(const std::string &s, const std::string &needle) {
  return s.find(needle) != std::string::npos;
}

const char *kFloatOps = R"(kernel k(float* f, float a, float b, int* o) {
  f[0] = a + b; f[1] = a - b; f[2] = a * b; f[3] = a / b; f[4] = sqrt(a);
  if (a == b) { o[0] = 1; } if (a != b) { o[1] = 1; } if (a < b) { o[2] = 1; }
  if (a <= b) { o[3] = 1; } if (a > b) { o[4] = 1; } if (a >= b) { o[5] = 1; }
  o[6] = (int)a; f[5] = (float)o[7]; f[6] = min(a, b) + max(a, b) + abs(-a);
})";

} // namespace

TEST(PtxImmediate, ExactHexBitPatterns) {
  EXPECT_EQ(ptx::f32Immediate(1.0f), "0f3F800000");
  EXPECT_EQ(ptx::f32Immediate(0.1f), "0f3DCCCCCD");
  EXPECT_EQ(ptx::f32Immediate(-0.0f), "0f80000000");
  EXPECT_EQ(ptx::f32Immediate(0.0f), "0f00000000");
  EXPECT_EQ(ptx::f32Immediate(1e-38f), "0f006CE3EE"); // subnormal survives exactly
  EXPECT_EQ(ptx::f32Immediate(-2.5f), "0fC0200000");
  EXPECT_EQ(ptx::f32Immediate(std::numeric_limits<float>::max()), "0f7F7FFFFF");
}

TEST(PtxImmediate, InfinityCannotComeFromSource) {
  // The lexer rejects overflowing literals, so an inf immediate can only come from folding.
  std::string src = "kernel k(float* f) { f[0] = 1e39; }";
  DiagEngine diag("t.tc", src);
  parseSource(src, diag);
  EXPECT_TRUE(diag.hasErrors());
}

TEST(PtxLabel, SanitizesIrLabels) {
  EXPECT_EQ(ptx::ptxLabel("if.then.1"), "$L__if_then_1");
  EXPECT_EQ(ptx::ptxLabel("exit"), "$L__exit");
}

TEST(PtxEmitter, ModuleHeader) {
  std::string p = toPtx("kernel k(int* o) { o[0] = 1; }", "sm_80");
  EXPECT_TRUE(has(p, ".version 7.0\n.target sm_80\n.address_size 64\n")) << p;
  EXPECT_TRUE(has(p, "// Generated by TinyCU")) << p;
  EXPECT_TRUE(has(p, ".visible .entry k(\n\t.param .u64 k_param_0\n)")) << p;
}

TEST(PtxEmitter, FloatArithmeticIsRoundToNearestAndNeverFused) {
  std::string p = toPtx(kFloatOps);
  for (const char *op : {"add.rn.f32", "sub.rn.f32", "mul.rn.f32", "div.rn.f32", "sqrt.rn.f32",
                         "cvt.rzi.s32.f32", "cvt.rn.f32.s32", "min.f32", "max.f32", "abs.f32"})
    EXPECT_TRUE(has(p, op)) << op << "\n" << p;
  EXPECT_FALSE(std::regex_search(p, std::regex(R"(\b(add|sub|mul|div)\.f32)"))) << p;
  EXPECT_FALSE(has(p, "fma")) << p;
  EXPECT_FALSE(has(p, "mad")) << p;
}

TEST(PtxEmitter, FloatComparesFollowCSemantics) {
  std::string p = toPtx(kFloatOps);
  EXPECT_TRUE(has(p, "setp.eq.f32")) << p;
  EXPECT_TRUE(has(p, "setp.neu.f32")) << p; // != is unordered: true on NaN
  EXPECT_FALSE(has(p, "setp.ne.f32")) << p;
  for (const char *op : {"setp.lt.f32", "setp.le.f32", "setp.gt.f32", "setp.ge.f32"})
    EXPECT_TRUE(has(p, op)) << op;
}

TEST(PtxEmitter, IntComparesAreSigned) {
  std::string p = toPtx(
      "kernel k(int* o, int a, int b) { if (a != b && a < b || a >= b) { o[0] = a % b / b; } }");
  EXPECT_TRUE(has(p, "setp.ne.s32")) << p;
  EXPECT_TRUE(has(p, "setp.lt.s32")) << p;
  EXPECT_TRUE(has(p, "setp.ge.s32")) << p;
  EXPECT_TRUE(has(p, "rem.s32")) << p;
  EXPECT_TRUE(has(p, "div.s32")) << p;
}

TEST(PtxEmitter, PointerParamsConvertedToGlobal) {
  std::string p = toPtx("kernel k(float* x, int n) { x[n] = 1.0; }");
  EXPECT_TRUE(has(p, "ld.param.u64")) << p;
  EXPECT_TRUE(has(p, "cvta.to.global.u64")) << p;
  EXPECT_TRUE(has(p, "ld.param.s32")) << p;
  EXPECT_TRUE(has(p, "mul.wide.s32")) << p;
  EXPECT_TRUE(has(p, "st.global.f32")) << p;
  EXPECT_TRUE(has(p, ", 0f3F800000;")) << p;
}

TEST(PtxEmitter, SharedMemoryAndBarrier) {
  std::string p = toPtx(R"(kernel k(int* o) {
    shared int s[64]; s[threadIdx.x] = 1; __syncthreads(); o[0] = s[63]; })");
  EXPECT_TRUE(has(p, ".shared .align 4 .b8 __shared_s[256];")) << p;
  EXPECT_TRUE(has(p, "mov.u64")) << p;
  EXPECT_TRUE(has(p, "st.shared.s32")) << p;
  EXPECT_TRUE(has(p, "ld.shared.s32")) << p;
  EXPECT_TRUE(has(p, "bar.sync \t0;")) << p;
  EXPECT_TRUE(has(p, "mov.u32 \t%r")) << p;
  EXPECT_TRUE(has(p, "%tid.x")) << p;
}

TEST(PtxEmitter, BranchesOmitFallThrough) {
  std::string p = toPtx("kernel k(int* o, int n) { if (n > 0) { o[0] = 1; } else { o[0] = 2; } }");
  EXPECT_TRUE(has(p, "@!%p1 bra \t$L__if_else_1;")) << p; // then-block falls through
  EXPECT_TRUE(has(p, "bra.uni \t$L__if_end_1;")) << p;
  EXPECT_FALSE(has(p, "bra.uni \t$L__if_then_1;")) << p;
}

TEST(PtxEmitter, AllKernelsInOneModule) {
  std::string p = toPtx("kernel a(int* o) { o[0] = 1; }\nkernel b(int* o) { o[0] = 2; }");
  EXPECT_TRUE(has(p, ".visible .entry a(")) << p;
  EXPECT_TRUE(has(p, ".visible .entry b(")) << p;
  EXPECT_EQ(p.find(".version"), p.rfind(".version")); // one header
}

TEST(PtxEmitter, Deterministic) { EXPECT_EQ(toPtx(kFloatOps), toPtx(kFloatOps)); }

TEST(PtxEmitter, RegisterDeclarationsCoverEveryUse) {
  std::string p = toPtx(kFloatOps);
  std::map<std::string, int> declared;
  std::regex decl(R"(\.reg \.\w+ \t(%[a-z]+)<(\d+)>;)");
  for (auto it = std::sregex_iterator(p.begin(), p.end(), decl); it != std::sregex_iterator(); ++it)
    declared[(*it)[1]] = std::stoi((*it)[2]);
  ASSERT_FALSE(declared.empty());
  std::regex use(R"((%(?:rd|r|f|p))(\d+)\b)");
  for (auto it = std::sregex_iterator(p.begin(), p.end(), use); it != std::sregex_iterator();
       ++it) {
    std::string cls = (*it)[1];
    int idx = std::stoi((*it)[2]);
    ASSERT_TRUE(declared.count(cls)) << cls;
    EXPECT_GE(idx, 1);
    EXPECT_LT(idx, declared[cls]) << cls << idx;
  }
}

TEST(PtxEmitter, NamedVariableComments) {
  std::string p = toPtx("kernel k(int* o, int n) { int count = n * 2; o[0] = count; }");
  EXPECT_TRUE(has(p, "// %count")) << p;
  ptx::Options o;
  o.comments = false;
  std::string src = "kernel k(int* o, int n) { int count = n * 2; o[0] = count; }";
  DiagEngine diag("t.tc", src);
  auto prog = parseSource(src, diag);
  ASSERT_TRUE(Sema(diag).run(*prog));
  EXPECT_FALSE(has(ptx::emitModule(*lowerProgram(*prog), o), "// %count"));
}
